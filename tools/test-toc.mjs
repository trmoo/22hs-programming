#!/usr/bin/env node
/**
 * 목차 강조 판정 테스트
 *
 * 브라우저 없이 순수 함수를 검증한다. Node 22.6+ 의 타입 스트리핑으로 .ts 를 직접 읽는다.
 *   node tools/test-toc.mjs
 */
import { 강조할제목 } from '../src/lib/toc.ts';

let 통과 = 0;
let 실패 = 0;

function 확인(설명, 실제, 기대) {
  const ok = 실제 === 기대;
  if (ok) {
    통과++;
    console.log(`  ok   ${설명}`);
  } else {
    실패++;
    console.log(`  FAIL ${설명}\n       기대: ${기대}  실제: ${실제}`);
  }
}

/* 차시 페이지의 전형적인 제목 배치 (히어로가 커서 첫 제목이 아래에 있다) */
const 제목들 = [
  { id: 'objectives', top: 420 },
  { id: 'standards', top: 700 },
  { id: 'body', top: 900 },
  { id: 'activities', top: 1300 },
  { id: 'prereq', top: 1600 },
  { id: 'reference', top: 1850 },
];
const 문서높이 = 2282;
const 화면높이 = 900;

console.log('강조할제목()');

확인('제목이 없으면 null', 강조할제목([], 0), null);

확인('맨 위(scrollY=0)에서는 첫 제목을 강조한다', 강조할제목(제목들, 0), 'objectives');

확인('첫 제목 직전에도 첫 제목을 강조한다', 강조할제목(제목들, 250), 'objectives');

확인('기준선이 첫 제목을 지나면 첫 제목', 강조할제목(제목들, 310), 'objectives');

확인('두 번째 제목을 지나면 두 번째', 강조할제목(제목들, 600), 'standards');

확인('세 번째 제목을 지나면 세 번째', 강조할제목(제목들, 816), 'body');

확인('네 번째 제목 직전에는 여전히 세 번째', 강조할제목(제목들, 1100), 'body');

확인('네 번째 제목을 지나면 네 번째', 강조할제목(제목들, 1200), 'activities');

확인(
  '문서 맨 아래에서는 마지막 제목을 강조한다',
  강조할제목(제목들, 문서높이 - 화면높이, 120, 문서높이, 화면높이),
  'reference'
);

확인(
  '맨 아래 판정은 문서가 화면보다 길 때만 적용한다',
  강조할제목(제목들, 0, 120, 500, 900),
  'objectives'
);

/* 경계: 제목 top 이 기준선과 정확히 같을 때 그 제목을 고른다 */
확인('기준선과 제목이 정확히 같으면 그 제목', 강조할제목(제목들, 300), 'objectives');

/* 짧은 문서 — 제목 하나 */
확인('제목이 하나면 항상 그것', 강조할제목([{ id: 'only', top: 500 }], 0), 'only');

/* offset 을 0 으로 주면 화면 최상단 기준 */
확인('offset=0 이면 제목 top 이 scrollY 이하일 때만', 강조할제목(제목들, 419, 0), 'objectives');
확인('offset=0, 첫 제목보다 위면 첫 제목', 강조할제목(제목들, 100, 0), 'objectives');

console.log(`\n${실패 === 0 ? '통과' : '실패'} — ${통과}건 통과, ${실패}건 실패`);
process.exit(실패 === 0 ? 0 : 1);
